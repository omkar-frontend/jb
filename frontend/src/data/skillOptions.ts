function toOption(name: string): SkillOption {
    return { value: name, label: name }
}

export const SKILL_OPTIONS: SkillOption[] = [...new Set(SKILL_NAMES)]
    .sort((a, b) => a.localeCompare(b))
    .map(toOption)

/** Include CV skills not in the master list so they remain selectable. */
export function mergeSkillOptions(selectedSkills: string[]): SkillOption[] {
    const known = new Set(
        SKILL_OPTIONS.map((option) => option.value.toLowerCase())
    )
    const extras = selectedSkills
        .map((skill) => skill.trim())
        .filter((skill) => skill && !known.has(skill.toLowerCase()))
        .map(toOption)

    return [...SKILL_OPTIONS, ...extras]
}

export function skillsToSelectValue(skills: string[]): SkillOption[] {
    return skills.map((skill) => toOption(skill))
}
